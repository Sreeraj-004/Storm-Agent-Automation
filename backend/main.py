@app.post(
    "/storm-mode/exceptions/{alert_id}/{sys_id}/decision"
)
async def decide_change_exception(
    alert_id: str,
    sys_id: str,
    payload: ExceptionDecision,
):
    exception = get_exception(alert_id, sys_id)

    if not exception:
        raise HTTPException(
            status_code=404,
            detail="Change exception not found.",
        )

    if exception.get("exception_status") != "pending":
        raise HTTPException(
            status_code=409,
            detail="This exception is no longer pending.",
        )

    if exception.get("risk_assessment", {}).get(
        "risk_classification"
    ) != "high":
        raise HTTPException(
            status_code=400,
            detail="Only high-risk exceptions can be decided here.",
        )

    # Write the decision note to ServiceNow first.
    # If this fails, do not mark the exception as completed.
    try:
        note_result = await update_exception_decision_work_note(
            sys_id,
            payload.decision,
        )
    except Exception as exc:
        logger.exception(   
            "Failed to record exception decision for %s", sys_id
        )
        raise HTTPException(
            status_code=502,
            detail=(
                "Could not confirm the decision work note in "
                "ServiceNow. Check ServiceNow before retrying."
            ),
        ) from exc

    updated = complete_exception_decision(
        alert_id=alert_id,
        sys_id=sys_id,
        decision=(
            "approved"
            if payload.decision == "approve"
            else "rejected"
        ),
        note_status="updated",
    )

    if not updated:
        raise HTTPException(
            status_code=409,
            detail=(
                "The work note was sent, but the exception state "
                "changed concurrently. Verify ServiceNow and "
                "reconcile the local record."
            ),
        )

    return {
        "status": "success",
        "alert_id": alert_id,
        "sys_id": sys_id,
        "decision": payload.decision,
        "exception_status": (
            "approved"
            if payload.decision == "approve"
            else "rejected"
        ),
        "work_note_status": note_result["status"],
    }

@app.post("/storm-mode/requests/{alert_id}/process")
async def resume_storm_processing(alert_id: str):
    alert = get_storm(alert_id)

    if not alert:
        raise HTTPException(
            status_code=404,
            detail="Storm request not found.",
        )

    if alert.get("status") != "approved":
        raise HTTPException(
            status_code=409,
            detail="Only approved storm requests can be processed.",
        )

    try:
        start = datetime.fromisoformat(alert["suggested_start"])
        end = datetime.fromisoformat(alert["suggested_end"])

        if start.tzinfo is None or end.tzinfo is None or end <= start:
            raise ValueError("Invalid storm date range.")

    except (KeyError, TypeError, ValueError) as exc:
        raise HTTPException(
            status_code=400,
            detail="The storm date range is invalid.",
        ) from exc

    result = await process_storm_changes(start, end, alert_id)

    return {
        "alert_id": alert_id,
        "freeze_result": result,
    }


@app.post("/storm-mode/requests/{alert_id}/close")
async def close_storm_mode(alert_id: str):
    # 1. Retrieve the Storm Mode request
    alert = get_storm(alert_id)

    if not alert:
        raise HTTPException(
            status_code=404,
            detail="Storm Mode request not found.",
        )

    # 2. Only approved Storm Mode requests can be closed
    if alert.get("status") != "approved":
        raise HTTPException(
            status_code=409,
            detail="Only approved Storm Mode can be closed.",
        )

    # 3. Validate the storm time window
    try:
        start = datetime.fromisoformat(
            alert["suggested_start"]
        )
        end = datetime.fromisoformat(
            alert["suggested_end"]
        )

        if (
            start.tzinfo is None
            or end.tzinfo is None
            or end <= start
        ):
            raise ValueError("Invalid storm date range.")

        start = start.astimezone(timezone.utc)
        end = end.astimezone(timezone.utc)

    except (KeyError, TypeError, ValueError) as exc:
        raise HTTPException(
            status_code=400,
            detail="Invalid storm date range.",
        ) from exc

    # 4. Validate ServiceNow configuration
    if not all([
        SNOW_INSTANCE_URL,
        SNOW_USERNAME,
        SNOW_PASSWORD,
    ]):
        raise HTTPException(
            status_code=500,
            detail="ServiceNow configuration is incomplete.",
        )

    url = (
        f"{SNOW_INSTANCE_URL}"
        "/api/now/table/change_request"
    )

    # Use the same scheduled-change overlap logic
    # as the existing Storm Mode changes endpoint.
    start_value = start.strftime("%Y-%m-%d %H:%M:%S")
    end_value = end.strftime("%Y-%m-%d %H:%M:%S")

    params = {
        "sysparm_query": (
            f"start_date<={end_value}"
            f"^end_date>={start_value}"
            "^ORDERBYstart_date"
        ),
        "sysparm_fields": "sys_id,number",
        "sysparm_limit": "100",
    }

    close_note = (
        "Storm Mode ended. The change freeze is lifted. "
        "Proceed with the change as per the original "
        "scheduled implementation window."
    )

    results = {
        "success_count": 0,
        "failed_count": 0,
        "changes": [],
    }

    # 5. Fetch matching changes and add the work note
    try:
        async with httpx.AsyncClient(
            timeout=30.0,
            follow_redirects=False,
            verify=False,
        ) as client:

            response = await client.get(
                url,
                params=params,
                auth=(SNOW_USERNAME, SNOW_PASSWORD),
                headers={"Accept": "application/json"},
            )

            response.raise_for_status()

            changes = response.json().get("result", [])

            
            for change in changes:
                change_number = change.get("number")
                sys_id = change.get("sys_id")

                if not sys_id:
                    results["failed_count"] += 1
                    results["changes"].append({
                        "number": change_number,
                        "status": "failed",
                        "error": "ServiceNow record has no sys_id.",
                    })
                    continue

                try:
                    update_response = await snow_request_with_retry(
                        client,
                        "PATCH",
                        f"{url}/{sys_id}",
                        auth=(SNOW_USERNAME, SNOW_PASSWORD),
                        headers={
                            "Accept": "application/json",
                            "Content-Type": "application/json",
                        },
                        json={
                            "work_notes": close_note,
                            "on_hold": False,
                        },
                    )

                    results["success_count"] += 1
                    results["changes"].append({
                        "number": change_number,
                        "status": "success",
                        "work_note": "added",
                        "hold_released": True,
                    })

                except Exception as exc:
                    logger.exception(
                        "Failed to update change %s while closing Storm Mode",
                        change_number,
                    )

                    results["failed_count"] += 1
                    results["changes"].append({
                        "number": change_number,
                        "status": "failed",
                        "error": str(exc),
                    })


    except httpx.HTTPStatusError as exc:
        logger.error(
            "ServiceNow close request failed with HTTP %s",
            exc.response.status_code,
        )
        raise HTTPException(
            status_code=502,
            detail="ServiceNow rejected the change lookup request.",
        ) from exc

    except httpx.RequestError as exc:
        logger.exception(
            "Unable to connect to ServiceNow while closing Storm Mode."
        )
        raise HTTPException(
            status_code=502,
            detail="Unable to connect to ServiceNow.",
        ) from exc

    except (ValueError, KeyError) as exc:
        logger.exception(
            "Invalid response while retrieving ServiceNow changes."
        )
        raise HTTPException(
            status_code=502,
            detail="Unable to process the ServiceNow response.",
        ) from exc

    # 6. Do not close Storm Mode if any work note failed
    if results["failed_count"] > 0:
        raise HTTPException(
            status_code=502,
            detail={
                "message": (
                    "Some work notes failed. "
                    "Storm Mode remains open."
                ),
                "result": results,
            },
        )

    # 7. Mark Storm Mode as closed only after all updates succeed
    alert["status"] = "closed"
    alert["closed_at"] = datetime.now(
        timezone.utc
    ).isoformat()

    save_storm(alert)

    return {
        "status": "success",
        "storm_status": "closed",
        "message": (
            "Storm Mode closed successfully. "
            "Work notes were added to all matching changes."
        ),
        "work_notes": results,
    }
