@app.get("/storm-mode/changes")
async def get_scheduled_changes(
    test_connection: bool = Query(False),
):
    if not all([
        SNOW_INSTANCE_URL,
        SNOW_USERNAME,
        SNOW_PASSWORD,
    ]):
        raise HTTPException(
            status_code=500,
            detail="ServiceNow configuration is incomplete.",
        )

    url = f"{SNOW_INSTANCE_URL}/api/now/table/change_request"

    params = {"sysparm_limit": "1"}

    alert = None

    if not test_connection:
        approved_alerts = [
            item
            for item in list_storms()
            if item.get("status") == "approved"
        ]

        if not approved_alerts:
            raise HTTPException(
                status_code=404,
                detail="No approved storm alerts found.",
            )

        alert = approved_alerts[0]

        try:
            start = datetime.fromisoformat(
                alert["suggested_start"]
            )
            end = datetime.fromisoformat(
                alert["suggested_end"]
            )
        except (ValueError, TypeError, KeyError) as exc:
            raise HTTPException(
                status_code=400,
                detail="Invalid storm date range.",
            ) from exc

        if end <= start:
            raise HTTPException(
                status_code=400,
                detail="Storm end must be after its start.",
            )

        start = start.astimezone(timezone.utc)
        end = end.astimezone(timezone.utc)

        start_value = start.strftime("%Y-%m-%d %H:%M:%S")
        end_value = end.strftime("%Y-%m-%d %H:%M:%S")

        params = {
            "sysparm_query": (
                f"start_date<={end_value}"
                f"^end_date>={start_value}"
                "^ORDERBYstart_date"
            ),
            "sysparm_fields": (
                "sys_id,number,short_description,description,"
                "type,state,approval,start_date,end_date,"
                "assignment_group,requested_by"
            ),
            "sysparm_display_value": "true",
            "sysparm_limit": "100",
        }

    try:
        async with httpx.AsyncClient(
            timeout=30.0,
            follow_redirects=False,
            verify=False,
        ) as client:
            response = await client.get(
                url,
                params=params,
                auth=(SNOW_USERNAME, SNOW_PASSWORD),
                headers={"Accept": "application/json"},
            )

        if response.status_code >= 300:
            logger.error(
                "ServiceNow status=%s, location=%s, body=%s",
                response.status_code,
                response.headers.get("location"),
                response.text[:1000],
            )

            raise HTTPException(
                status_code=502,
                detail={
                    "message": "ServiceNow request failed.",
                    "snow_status": response.status_code,
                    "redirect_location": response.headers.get(
                        "location"
                    ),
                    "snow_response": response.text[:1000],
                },
            )

        data = response.json()
        changes = data.get("result", [])

    except httpx.RequestError as exc:
        logger.exception("ServiceNow connection failed")
        raise HTTPException(
            status_code=502,
            detail="Unable to connect to ServiceNow.",
        ) from exc

    if test_connection:
        return {
            "status": "connected",
            "records_returned": len(changes),
        }

    return {
        "location": alert["location"],
        "storm_period": {
            "start": start.isoformat(),
            "end": end.isoformat(),
        },
        "count": len(changes),
        "changes": changes,
    }

@app.post("/storm-mode/requests/{alert_id}/decision")
async def decide_storm_mode(
    alert_id: str,
    payload: StormModeDecision,
):
    alert = get_storm(alert_id)

    if alert is None:
        raise HTTPException(
            status_code=404,
            detail="Storm Mode request not found.",
        )

    if alert["status"] != "pending":
        raise HTTPException(
            status_code=409,
            detail=f"Request already {alert['status']}.",
        )

    # Update the storm request.
    alert.update({
        "location": payload.location.strip(),
        "event": payload.event.strip(),
        "severity": payload.severity,
        "description": payload.description.strip(),
        "suggested_start": payload.suggested_start.isoformat(),
        "suggested_end": payload.suggested_end.isoformat(),
        "status": (
            "approved"
            if payload.decision == "approve"
            else "rejected"
        ),
        "decision_by": None,
        "decision_at": datetime.now(timezone.utc).isoformat(),
        
    })
    save_storm(alert)

    freeze_result = None
    processing_result = None

    # Apply the change freeze only when Storm Mode is approved.
    if payload.decision == "approve":
        processing_result = await process_storm_changes(
            payload.suggested_start,
            payload.suggested_end,
            alert_id,
        )

    return {
    "message": (
        "Storm Mode approved."
        if payload.decision == "approve"
        else "Storm Mode rejected."
    ),
    "alert": alert,
    "freeze_result": processing_result,
}



